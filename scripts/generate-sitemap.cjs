const fs = require('node:fs');
const base = (process.env.NEXT_PUBLIC_SITE_URL || 'https://rufes-home-and-lifestyle.pages.dev').replace(/\/$/, '');
const slugs = source => [...source.matchAll(/slug:\s*["']([^"']+)["']/g)].map(m => m[1]);
const catalogue = fs.readFileSync('lib/catalog.ts', 'utf8');
const content = fs.readFileSync('lib/content.ts', 'utf8');
const products = slugs(catalogue.split('export const categories')[0]);
const categories = slugs(catalogue.split('export const categories')[1].split('export const photos')[0]);
const services = slugs(content.split('export const articles')[0]);
const articles = slugs(content.split('export const articles')[1]);
const paths = ['/', '/about/', '/contact/', '/showroom/', '/collections/', '/services/', '/blog/', '/gallery/', '/faqs/', '/privacy/', '/terms/', ...products.map(s => '/products/' + s + '/'), ...categories.map(s => '/collections/' + s + '/'), ...services.map(s => '/services/' + s + '/'), ...articles.map(s => '/blog/' + s + '/')];
const xml = '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' + paths.map(p => '  <url><loc>' + base + p + '</loc></url>').join('\n') + '\n</urlset>\n';
fs.writeFileSync('public/sitemap.xml', xml);
fs.writeFileSync('public/robots.txt', 'User-agent: *\nAllow: /\nSitemap: ' + base + '/sitemap.xml\n');
console.log('Generated', paths.length, 'sitemap URLs for', base);
